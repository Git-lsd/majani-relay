"""Write results/RESULTS.md and results/numbers.json from metrics.json (numbers are never typed by hand).
Run: ../.venv/bin/python ml/write_results_md.py"""
import os, json

HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(HERE); RES = os.path.join(REPO, 'results')
M = json.load(open(os.path.join(RES, 'metrics.json')))
O = json.load(open(os.path.join(RES, 'onnx_check.json')))
D = json.load(open(os.path.join(RES, 'data_stats.json')))
L = M['learning_loop']; ks = L['ks']; pa = L['curves']['prior_adapt']; lo = L['curves']['local_only']
V = M['village_sim']; f = M['field']; c = M['in_domain_calib']
pct = lambda x: f'{100 * x:.0f}%'
i10, i50, i200 = ks.index(10), ks.index(50), ks.index(200)
N = {
    'MODEL_MB': f"{O['onnx_mb']:.1f}", 'HEAD_KB': f"{O['head_kb']:.0f}", 'REF_KB': f"{O['reference_kb']:.0f}",
    'LATENCY_MS_LAPTOP': f"{O['cpu_ms_per_image_laptop']:.0f}",
    'LAB_ACC': pct(c['acc_all']), 'LAB_COVERAGE': pct(c['coverage']), 'LAB_ACC_ANSWERED': pct(c['acc_answered']),
    'FIELD_ACC_NO_ABSTAIN': f"{100 * f['acc_all']:.1f}%", 'FIELD_MEAN_CONFIDENCE': pct(f['mean_confidence']),
    'FIELD_NOT_SURE': f"{100 * (1 - f['coverage']):.1f}%", 'MITE_NOT_SURE': pct(M['mite']['abstain_rate']),
    'AUROC_KNN': f"{M['ood_auroc_field_vs_heldout']['knn10_cosine (used)']:.3f}",
    'AUROC_CONFIDENCE': f"{M['ood_auroc_field_vs_heldout']['max_softmax']:.2f}",
    'COV_10': pct(pa['coverage'][i10]), 'ACC_ANS_10': pct(pa['acc_answered'][i10]), 'ACC_ANS_10_LOCAL_ONLY': pct(lo['acc_answered'][i10]),
    'COV_50': pct(pa['coverage'][i50]), 'ACC_ANS_50': pct(pa['acc_answered'][i50]),
    'ACC_ANS_50_LOCAL_ONLY': pct(lo['acc_answered'][i50]), 'ACC_ANS_200_LOCAL_ONLY': pct(lo['acc_answered'][i200]),
    'COV_200': pct(pa['coverage'][i200]), 'ACC_ANS_200': pct(pa['acc_answered'][i200]),
    'UPDATE_KB_HEAD': f"{L['update_bytes_float16_head'] / 1e3:.0f}",
    'UPDATE_BYTES_PER_PHOTO': f"{L['update_bytes_int8_per_reference_photo']}",
    'VILLAGE_FA_RAW': f"{V['raw']['false_alarms']:.1f}", 'VILLAGE_FA_ADJ': f"{V['shrunk']['false_alarms']:.1f}",
    'VILLAGE_MISS_RAW': f"{V['raw']['missed']:.1f}", 'VILLAGE_MISS_ADJ': f"{V['shrunk']['missed']:.1f}",
    'VILLAGE_TOP5_RAW': f"{V['raw']['top5_hits']:.1f}", 'VILLAGE_TOP5_ADJ': f"{V['shrunk']['top5_hits']:.1f}",
    'VILLAGE_HOT': f"{V['mean_true_hot_villages']:.1f}", 'ALERT_RATE': '25%', 'ALERT_PROB': '0.5',
    'N_TRAIN': str(M['n']['train']), 'N_CALIB': str(M['n']['calib']), 'N_FIELD': str(M['n']['field']), 'N_MITE': str(M['n']['mite']),
}
alt = M.get('alt_backbone_dinov2_small')
if alt:
    N['DINO_FIELD_ACC'] = pct(alt['field_acc_no_local_labels'])
    N['DINO_COV_50'] = pct(alt['loop_prior_adapt']['50']['coverage']); N['DINO_ACC_ANS_50'] = pct(alt['loop_prior_adapt']['50']['acc_answered'])
# optional: human baseline (picture card vs AI), only if ml/score_baseline.py has written results/human_baseline.json
HBP = os.path.join(RES, 'human_baseline.json')
HB = json.load(open(HBP)) if os.path.exists(HBP) else None
if HB and not HB.get('labellers'):
    HB = None
if HB:
    hum = HB['labellers']; ai0 = HB['model']['shipped']; ai1 = HB['model']['after_demo_update_50']
    def rng_(vals, fmt):
        v = [x for x in vals if x is not None]
        if not v:
            return '-'
        lo_, hi_ = fmt(min(v)), fmt(max(v))
        return lo_ if lo_ == hi_ else f'{lo_}–{hi_}'
    N.update({'HB_N_LABELLERS': str(len(hum)), 'HB_N_PHOTOS': str(HB['photo_set']['n']),
              'HB_HUMAN_ANSWERED': rng_([h['share_answered'] for h in hum], pct),
              'HB_HUMAN_ACC_ANSWERED': rng_([h['acc_answered'] for h in hum], pct),
              'HB_HUMAN_HVP': rng_([h['acc_healthy_vs_problem_answered'] for h in hum], pct),
              'HB_HUMAN_CORRECT_OF_ALL': rng_([h['correct_of_all'] for h in hum], pct),
              'HB_HUMAN_MEDIAN_SECONDS': rng_([h['median_seconds'] for h in hum], lambda x: f'{x:.1f}'),
              'HB_AI_SHIPPED_NOT_SURE': pct(1 - ai0['share_answered']),
              'HB_AI_UPD_ANSWERED': pct(ai1['share_answered']), 'HB_AI_UPD_ACC_ANSWERED': pct(ai1['acc_answered']),
              'HB_AI_UPD_HVP': pct(ai1['acc_healthy_vs_problem_answered']), 'HB_AI_UPD_CORRECT_OF_ALL': pct(ai1['correct_of_all'])})
json.dump(N, open(os.path.join(RES, 'numbers.json'), 'w'), indent=1)

md = f"""# Results (generated by ml/write_results_md.py from results/metrics.json — do not edit by hand)

## What the phone runs
- Frozen MobileNetV3-Large image backbone (ImageNet weights, Apache-2.0): **{N['MODEL_MB']} MB** ONNX, ~{N['LATENCY_MS_LAPTOP']} ms per photo on a laptop CPU (phone speed not yet measured).
- Small head: **{N['HEAD_KB']} KB** JSON. Familiarity reference (1,000 stored training photos as int8 vectors): **{N['REF_KB']} KB**.
- The ONNX path reproduces the Python pipeline: {O['onnx_vs_python_same_class']} same class, max embedding difference {O['onnx_vs_python_max_abs_diff']}.

## Data
- Training: {N['N_TRAIN']} photos — 1,500 sampled per class from JMuBEN/JMuBEN2 (Kenya, Kirinyaga, arabica; 58,550 images, many are rotated/flipped copies) plus half of the BRACOL photos we could recover (Brazil, arabica; Mendeley archive is truncated, 1,342 usable of 1,747).
- Calibration (temperature, threshold, familiarity cutoff): the other half of BRACOL ({N['N_CALIB']} photos).
- Sealed field test: RoCoLe (Ecuador, robusta, on-plant smartphone photos) — {N['N_FIELD']} healthy/rust photos; {N['N_MITE']} red-spider-mite photos as an out-of-scope test.

## Findings
1. **Lab accuracy does not transfer to the field.** On held-out lab-style photos the model is right {N['LAB_ACC']} of the time. On field photos it is right {N['FIELD_ACC_NO_ABSTAIN']} of the time, while reporting {N['FIELD_MEAN_CONFIDENCE']} average confidence. A tool that trusted its own confidence would give confident wrong answers.
2. **The familiarity check catches this.** Comparing each photo with the 1,000 stored training photos separates field photos from lab photos almost perfectly (AUROC {N['AUROC_KNN']}; model confidence alone scores {N['AUROC_CONFIDENCE']}, worse than chance). Out of the box the tool says "not sure — the officer will look" to **{N['FIELD_NOT_SURE']}** of field photos and **{N['MITE_NOT_SURE']}** of photos of a pest it was never trained on.
3. **The learning loop localises the model.** When the officer labels field photos, the head is refit on the phone (pulled toward the lab model) and the labelled photos join the familiarity reference:

| Officer labels | Photos answered | Answers correct | Answers correct, local labels only (no lab model) |
|---|---|---|---|
""" + '\n'.join(f"| {k} | {pct(pa['coverage'][i])} | {'—' if pa['acc_answered'][i] is None else pct(pa['acc_answered'][i])} | {'—' if lo['acc_answered'][i] is None else pct(lo['acc_answered'][i])} |" for i, k in enumerate(ks)) + f"""

   Starting from the lab model matters most when labels are few ({N['ACC_ANS_10']} vs {N['ACC_ANS_10_LOCAL_ONLY']} correct at 10 labels). An update to share with other phones is ~{N['UPDATE_KB_HEAD']} KB for the head plus {N['UPDATE_BYTES_PER_PHOTO']} bytes per labelled photo.
4. **Village ranking (simulation, synthetic villages; ranks rust already seen, does not predict outbreaks).** Using the error rates measured after 50 officer labels, across 40 villages per round with about {N['VILLAGE_HOT']} real outbreaks: raw shares raise {N['VILLAGE_FA_RAW']} false alarms and miss {N['VILLAGE_MISS_RAW']} outbreaks per round; small-sample-adjusted shares (alert when the chance that the share is above 25% exceeds 0.5 — the same rule the app uses) raise {N['VILLAGE_FA_ADJ']} false alarms and miss {N['VILLAGE_MISS_ADJ']}. If the officer can visit 5 villages, the adjusted ranking sends them to {N['VILLAGE_TOP5_ADJ']} real outbreaks vs {N['VILLAGE_TOP5_RAW']} for raw shares. The adjustment trades fewer false alarms for more misses; villages below the alert line still appear in the ranked list.
"""
if alt:
    md += f"""5. **Size vs accuracy.** A 5x larger backbone (DINOv2-small, 21.6M parameters, ~87 MB) is right {N['DINO_FIELD_ACC']} of the time on field photos with no local labels (vs {N['FIELD_ACC_NO_ABSTAIN']}); after 50 labels it answers {N['DINO_COV_50']} of photos with {N['DINO_ACC_ANS_50']} correct. We ship the small model to respect the side-loading constraint.
"""
LIM = json.load(open(os.path.join(RES, 'limits.json')))['out_of_scope_pest_after_50_labels']
md += f"""6. **Limit found: unknown pests after adaptation.** Before local labels the tool says "not sure" to 100% of red-spider-mite photos (a pest it was never taught). After 50 officer labels it says "not sure" to only {pct(LIM['not_sure_after_50'])}; of the rest, {LIM['answered_as_after_50']['rust']} are flagged as rust (the officer still hears about a problem) and {LIM['answered_as_after_50']['healthy']} are wrongly called healthy. Mitigations in the app: a "different problem / not in list" label for the officer, and a spot-check that queues 1 in 10 answered photos for the officer anyway.
"""
if HB:
    nh = len(hum); ps = HB['photo_set']; rl = ps['rust_by_level']; chk = HB.get('model_on_resized_copies', {})
    p_ = lambda x: '—' if x is None else pct(x)
    sec_ = lambda x: '—' if x is None else f'{x:.1f}'
    group = {1: 'one team member', 2: 'two team members', 3: 'three team members'}.get(nh, f'{nh} team members')
    row_ = lambda who_, r, secs: (f"| {who_} | {p_(r['share_answered'])} | {p_(r['acc_answered'])} | "
                                  f"{p_(r['acc_healthy_vs_problem_answered'])} | {p_(r['correct_of_all'])} | {secs} |\n")
    levels = list(ai1['by_rust_level'].values())
    lvl_head = '| Who | ' + ' | '.join(f"{v['label'].capitalize()} ({v['n']})" for v in levels) + ' |\n|---|' + '---|' * len(levels) + '\n'
    lvl_row = lambda who_, r: f'| {who_} | ' + ' | '.join(pct(v['correct_of_all']) for v in r['by_rust_level'].values()) + ' |\n'
    same0 = chk.get('shipped', {}).get('same_decision_as_original', '?')
    same1 = chk.get('after_demo_update_50', {}).get('same_decision_as_original', '?')
    md += f"""
## Human baseline: picture card vs AI (one-evening test)
To compare the AI with a paper picture card, {group} labelled the same {ps['n']} field photos with only a picture card (two training pictures and one line per problem), on a phone or laptop. The AI was scored on the same photos with the same rule as the app.

| Who | Photos answered (not "not sure") | Answers correct | Healthy vs problem correct (of answered) | Correct out of all {ps['n']} | Median seconds per photo |
|---|---|---|---|---|---|
"""
    md += ''.join(row_(f"{h['name']} (picture card)", h, sec_(h['median_seconds'])) for h in hum)
    md += row_('AI as shipped (no local labels)', ai0, '—') + row_('AI after the demo update (50 labelled field photos)', ai1, '—')
    md += '\nRight answer by true class, out of all photos of that class ("not sure" counts as not right):\n\n' + lvl_head
    md += ''.join(lvl_row(h['name'], h) for h in hum) + lvl_row('AI after the demo update', ai1)
    md += f"""
What this test is and is not:
- {'The labeller is' if nh == 1 else 'The labellers are'} {group} who {'is not a farmer or plant expert' if nh == 1 else 'are not farmers or plant experts'}, standing in for relay farmers. Relay farmers trained by the cooperative may do better.
- {'The labeller' if nh == 1 else 'The labellers'} may have known that this dataset holds only healthy and rust leaves. A relay farmer would not know this, so the five-way choice was easier.
- {ps['n']} photos from one dataset (RoCoLe: Ecuador, robusta, leaves on the plant): {ps['healthy']} healthy and {sum(rl.values())} rust (rust levels 1 to 4: {', '.join(str(v) for v in rl.values())} photos). They are not photos from Kenyan farms.
- A one-evening test: each person labelled each photo once, with no training beyond the card.
- The AI as shipped says "not sure" to {pct(1 - ai0['share_answered'])} of these photos because they look unlike its training photos. The AI after the demo update has learned from 50 other photos of the same dataset (none of them among these {ps['n']}), labelled by the dataset authors in place of an officer.
- People saw copies resized to 900 px; the AI used the original photos. On the resized copies the AI makes the same decision on {same0} of {ps['n']} photos as shipped and on {same1} of {ps['n']} after the update.
"""
md += """
## Simplifications (stated)
- JMuBEN contains augmented copies of the same leaf; its in-domain validation score (100%) is optimistic and not used as a headline.
- No training or test photo comes from Kenyan farms in field conditions; the field test is Ecuadorian robusta. Leaf rust looks similar across species, but this is a proxy.
- Learning-loop labelled photos and test photos both come from RoCoLe (one region, one photographer), so adaptation is easier here than across real farms.
- The village simulation uses synthetic villages; only the classifier error rates are measured.
- Labels in the learning loop come from the dataset authors, standing in for an extension officer.
"""
open(os.path.join(RES, 'RESULTS.md'), 'w').write(md)
print(md[:600]); print(json.dumps(N, indent=0)[:800])
